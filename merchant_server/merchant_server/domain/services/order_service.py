"""
Order Service — CQRS order management with saga orchestration.
"""

from __future__ import annotations

import uuid
from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession

from merchant_server.domain.models.cart import Cart
from merchant_server.domain.models.order import Order, OrderItem
from merchant_server.domain.repositories.cart_repo import CartRepository
from merchant_server.domain.repositories.order_repo import OrderRepository
from shared.events.kafka_producer import publish_event
from shared.observability.logging import get_logger
from shared.observability.metrics import orders_created_total

logger = get_logger(__name__)


class OrderServiceError(Exception):
    pass


class OrderService:
    """Order lifecycle management — creation, status updates, and event publishing."""

    def __init__(self, session: AsyncSession) -> None:
        self.session = session
        self.order_repo = OrderRepository(session)
        self.cart_repo = CartRepository(session)

    async def create_order_from_cart(
        self,
        user_id: uuid.UUID,
        idempotency_key: str,
        shipping_address: dict[str, Any] | None = None,
        billing_address: dict[str, Any] | None = None,
        notes: str | None = None,
    ) -> Order:
        """Create an order from the user's active cart.

        This is the command side of CQRS — writes a new order and marks cart as checked out.
        Idempotency key prevents duplicate orders.
        """
        # Idempotency check
        existing = await self.order_repo.get_by_idempotency_key(idempotency_key)
        if existing:
            logger.info("order_idempotent_hit", order_id=str(existing.id), key=idempotency_key)
            return existing

        # Get cart
        cart = await self.cart_repo.get_active_cart(user_id)
        if cart is None or not cart.items:
            raise OrderServiceError("Cart is empty or does not exist")

        # Calculate totals
        subtotal = cart.subtotal
        tax_amount = round(subtotal * 0.0, 2)  # Tax calculation should be a separate service
        total_amount = subtotal + tax_amount

        # Create order
        order = Order(
            user_id=user_id,
            order_number="",  # Will be generated by repo
            subtotal=subtotal,
            tax_amount=tax_amount,
            total_amount=total_amount,
            shipping_address=shipping_address,
            billing_address=billing_address,
            notes=notes,
            idempotency_key=idempotency_key,
            saga_state="initiated",
        )

        # Create order items from cart items
        for cart_item in cart.items:
            order_item = OrderItem(
                listing_id=cart_item.listing_id,
                variant_id=cart_item.variant_id,
                item_type=cart_item.item_type,
                quantity=cart_item.quantity,
                unit_price=float(cart_item.unit_price),
                total_price=cart_item.line_total,
                metadata_={
                    "check_in": str(cart_item.check_in) if cart_item.check_in else None,
                    "check_out": str(cart_item.check_out) if cart_item.check_out else None,
                    "guests": cart_item.guests,
                },
            )
            order.items.append(order_item)

        order = await self.order_repo.create(order)

        # Mark cart as checked out
        await self.cart_repo.mark_checked_out(cart.id)

        orders_created_total.labels(order_type="mixed", service="merchant-server").inc()

        # Publish order created event
        await publish_event(
            topic="orders",
            event_type="order.created",
            payload={
                "order_id": str(order.id),
                "order_number": order.order_number,
                "user_id": str(user_id),
                "total_amount": float(order.total_amount),
                "currency": order.currency,
                "items_count": len(order.items),
            },
            source="merchant-server",
            key=str(order.id),
            aggregate_id=str(order.id),
        )

        logger.info(
            "order_created",
            order_id=str(order.id),
            order_number=order.order_number,
            total=float(order.total_amount),
            items=len(order.items),
        )

        return order

    async def get_order(self, order_id: uuid.UUID) -> Order | None:
        return await self.order_repo.get_by_id(order_id)

    async def list_user_orders(
        self, user_id: uuid.UUID, status: str | None = None, offset: int = 0, limit: int = 20
    ) -> tuple[list[Order], int]:
        return await self.order_repo.list_user_orders(user_id, status, offset, limit)

    async def list_merchant_orders(
        self, merchant_id: uuid.UUID, status: str | None = None, offset: int = 0, limit: int = 20
    ) -> tuple[list[Order], int]:
        """List orders that contain items from this merchant's listings."""
        return await self.order_repo.list_merchant_orders(merchant_id, status, offset, limit)

    async def list_all_orders(
        self, status: str | None = None, offset: int = 0, limit: int = 20
    ) -> tuple[list[Order], int]:
        """Admin: list all orders."""
        return await self.order_repo.list_all_orders(status, offset, limit)

    async def update_order_status(self, order_id: uuid.UUID, new_status: str) -> bool:
        """Update order status and publish event."""
        order = await self.order_repo.get_by_id(order_id)
        if order is None:
            return False

        old_status = order.status
        result = await self.order_repo.update_status(order_id, new_status)

        if result:
            await publish_event(
                topic="orders",
                event_type="order.status_changed",
                payload={
                    "order_id": str(order_id),
                    "previous_status": old_status,
                    "new_status": new_status,
                },
                source="merchant-server",
                key=str(order_id),
                aggregate_id=str(order_id),
            )

        return result

    async def cancel_order(self, order_id: uuid.UUID) -> bool:
        """Cancel an order — triggers compensation saga."""
        order = await self.order_repo.get_by_id(order_id)
        if order is None:
            return False
        if order.status in ("delivered", "completed", "refunded"):
            raise OrderServiceError(f"Cannot cancel order in status: {order.status}")

        return await self.update_order_status(order_id, "cancelled")
